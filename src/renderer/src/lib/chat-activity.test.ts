import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { createChatActivity } from './chat-activity'

describe('recent terminal output', () => {
  beforeEach(() => vi.useFakeTimers())
  afterEach(() => vi.useRealTimers())

  it('coalesces bursts, ignores empty fragments, and expires chats independently', () => {
    const publish = vi.fn()
    const activity = createChatActivity(publish)
    const one = activity.register('one')
    const two = activity.register('two')
    one.output('')
    expect(vi.getTimerCount()).toBe(0)
    for (let i = 0; i < 1000; i++) one.output('data')
    expect(publish).not.toHaveBeenCalled()
    expect(vi.getTimerCount()).toBe(1)
    vi.advanceTimersByTime(250)
    expect(publish.mock.lastCall?.[0]).toEqual(new Set(['one']))
    two.output('second')
    vi.advanceTimersByTime(250)
    expect(publish.mock.lastCall?.[0]).toEqual(new Set(['one', 'two']))
    vi.advanceTimersByTime(1750)
    one.output('extended')
    vi.advanceTimersByTime(500)
    expect(publish.mock.lastCall?.[0]).toEqual(new Set(['one']))
    expect(publish).toHaveBeenCalledTimes(3)
    one.output('')
    vi.advanceTimersByTime(2000)
    expect(publish.mock.lastCall?.[0]).toEqual(new Set())
    expect(vi.getTimerCount()).toBe(0)
    one.output('again')
    vi.advanceTimersByTime(250)
    expect(publish.mock.lastCall?.[0]).toEqual(new Set(['one']))
    activity.dispose()
  })

  it('does not republish unchanged sets during sustained traffic', () => {
    const publish = vi.fn()
    const activity = createChatActivity(publish)
    const session = activity.register('one')
    for (let i = 0; i < 100; i++) {
      session.output('redraw')
      vi.advanceTimersByTime(100)
      expect(vi.getTimerCount()).toBe(1)
    }
    expect(publish).toHaveBeenCalledTimes(1)
    vi.advanceTimersByTime(2500)
    expect(publish).toHaveBeenCalledTimes(2)
    expect(publish.mock.lastCall?.[0]).toEqual(new Set())
    expect(vi.getTimerCount()).toBe(0)
  })

  it('invalidates replaced and disposed callbacks, including reused chat identities', () => {
    const publish = vi.fn()
    const activity = createChatActivity(publish)
    const old = activity.register('one')
    old.output('old')
    vi.advanceTimersByTime(250)
    const replacement = activity.register('one')
    expect(publish.mock.lastCall?.[0]).toEqual(new Set())
    old.output('stale')
    old.dispose()
    replacement.output('fresh')
    vi.advanceTimersByTime(250)
    expect(publish.mock.lastCall?.[0]).toEqual(new Set(['one']))
    replacement.dispose()
    old.output('stale')
    replacement.output('stale')
    vi.advanceTimersByTime(3000)
    expect(publish).toHaveBeenCalledTimes(4)
    expect(vi.getTimerCount()).toBe(0)
    const pending = activity.register('one')
    pending.output('pending')
    activity.dispose()
    pending.output('stale')
    expect(vi.getTimerCount()).toBe(0)
  })

  it('uses elapsed time after throttling and clears published activity on teardown', () => {
    const publish = vi.fn()
    const activity = createChatActivity(publish)
    const one = activity.register('one')
    one.output('data')
    vi.advanceTimersByTime(250)
    vi.setSystemTime(Date.now() + 10_000)
    vi.advanceTimersByTime(250)
    expect(publish.mock.lastCall?.[0]).toEqual(new Set())
    one.output('again')
    vi.advanceTimersByTime(250)
    activity.dispose()
    expect(publish.mock.lastCall?.[0]).toEqual(new Set())
    expect(vi.getTimerCount()).toBe(0)
  })
})
